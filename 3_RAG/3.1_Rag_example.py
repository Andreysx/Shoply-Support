# Retrieval-Augmented Generation – подход, при котором перед вызовом модели сначала ищутся релевантные данные во внешнем источнике знаний,
# а затем они включаются в контекст входа модели. Проще говоря: перед тем как сформировать ответ, модель «подсматривает» в базе данных или документах то, про что спрашивают,
# чтобы получить релевантные данные и отвечать уже зная больше по теме вопроса.

# Ретривер (поисковый компонент) – принимает запрос пользователя и ищет релевантные фрагменты из Knowledge Base (заранее заданной базе знаний). 
# Поиск может быть ключевым (по словам) или семантическим (через эмбеддинги).
# Генеративная модель (LLM) – получает исходный вопрос + найденные куски информации и генерирует финальный ответ, используя предоставленный контекст.
# Типичный цикл RAG выглядит так: User Query → [Retriever] → Relevant Text Snippets → [LLM] → Answer
import os
from dotenv import load_dotenv
from langchain_openai import ChatOpenAI

load_dotenv()

MODEL = os.getenv("OPENAI_API_MODEL")

llm = ChatOpenAI(model_name=MODEL, temperature=0)

doc1 = "OpenAI была основана в декабре 2015 года. Цель компании – разработка ИИ для блага человечества."
doc2 = "МГУ – старейший университет в России, основанный в 1755 году. Расположен в Москве."
doc3 = "Париж называют городом любви. Он также знаменит своими историческими памятниками."

#  база
docs = [doc1, doc2, doc3]
user_question = "В каком году был основан МГУ?"

# Простой поиск: выберем документы, содержащие слово "основан"
relevant_docs = [d for d in docs if "основан" in d.lower() and ("мгу" in d.lower() or "университет" in d.lower())]

context = "\n".join(relevant_docs)  # склеим найденные фрагменты
prompt = f"Вопрос: {user_question}\nВот данные из источников: {context}\nОтвет:"
# print(prompt)

response = llm.invoke(prompt)
print(response.content)